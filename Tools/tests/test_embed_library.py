from __future__ import annotations

import io
import os
import re
import tempfile
import unittest
from contextlib import redirect_stderr
from pathlib import Path

from Tools import embed_library as embed

BYTES = re.compile(r"std::byte\{0x([0-9a-f]{2})\}")


def parsed_bytes(text: str) -> bytes:
    return bytes(int(match, 16) for match in BYTES.findall(text))


class HeaderTextTest(unittest.TestCase):
    def test_header_shape(self) -> None:
        text = embed.header_text("null", [("Standard", b"rojorhi.null")])
        self.assertTrue(text.startswith("// Generated by rojorhi.slang; do not edit.\n#pragma once\n\n#include <cstddef>\n"))
        self.assertIn("namespace rojoRHI::embedded {\n", text)
        self.assertIn("    /// The null shader library of Standard.slang.\n", text)
        self.assertIn("    inline constexpr std::byte kStandardLibrary[] = {\n", text)
        self.assertIn("        std::byte{0x72}, std::byte{0x6f}", text)
        self.assertTrue(text.endswith("} // namespace rojoRHI::embedded\n"))

    def test_rows_of_sixteen(self) -> None:
        text = embed.header_text("metal4", [("A", bytes(range(40)))])
        rows = [line for line in text.splitlines() if line.startswith("        std::byte")]
        self.assertEqual([row.count("std::byte") for row in rows], [16, 16, 8])

    def test_byte_count_preserved(self) -> None:
        data = bytes(range(256)) + b"tail"
        self.assertEqual(parsed_bytes(embed.header_text("d3d12", [("A", data)])), data)

    def test_libraries_keep_the_given_order(self) -> None:
        text = embed.header_text("null", [("Zed", b"z"), ("Alpha", b"a")])
        self.assertLess(text.index("kZedLibrary"), text.index("kAlphaLibrary"))
        self.assertIn("};\n\n    /// The null shader library of Alpha.slang.", text)


class WriteIfChangedTest(unittest.TestCase):
    def test_unchanged_text_is_not_rewritten(self) -> None:
        with tempfile.TemporaryDirectory() as name:
            path = Path(name) / "h.h"
            self.assertTrue(embed.write_if_changed(path, "text\n"))
            os.utime(path, (1_000_000, 1_000_000))
            self.assertFalse(embed.write_if_changed(path, "text\n"))
            self.assertEqual(path.stat().st_mtime, 1_000_000)
            self.assertEqual(path.read_text(), "text\n")

    def test_rewrites_when_format_changes(self) -> None:
        with tempfile.TemporaryDirectory() as name:
            path = Path(name) / "h.h"
            data = b"rojorhi"
            self.assertTrue(embed.write_if_changed(path, embed.header_text("metal4", [("A", data)])))
            self.assertTrue(embed.write_if_changed(path, embed.header_text("null", [("A", data)])))
            self.assertIn("The null shader library", path.read_text())

    @unittest.skipIf(os.name == "nt", "POSIX permission bits")
    def test_header_takes_the_umask_mode(self) -> None:
        with tempfile.TemporaryDirectory() as name:
            path = Path(name) / "h.h"
            previous = os.umask(0o022)
            try:
                embed.write_if_changed(path, "text\n")
            finally:
                os.umask(previous)
            self.assertEqual(path.stat().st_mode & 0o777, 0o644)

    def test_failed_write_leaves_no_temporary_file(self) -> None:
        with tempfile.TemporaryDirectory() as name:
            directory = Path(name)
            path = directory / "h.h"
            path.mkdir()
            with self.assertRaises(OSError):
                embed.write_if_changed(path, "text\n")
            self.assertEqual([entry.name for entry in directory.iterdir()], ["h.h"])


class MainTest(unittest.TestCase):
    def run_main(self, directory: Path, libraries: list[str], fmt: str = "null") -> tuple[int, str]:
        argv = ["--out", str(directory / "h.h"), "--format", fmt]
        for library in libraries:
            argv += ["--library", library]
        err = io.StringIO()
        with redirect_stderr(err):
            code = embed.main(argv)
        return code, err.getvalue()

    def test_writes_header(self) -> None:
        with tempfile.TemporaryDirectory() as name:
            directory = Path(name)
            (directory / "S.nulllib").write_bytes(b"abc")
            code, _ = self.run_main(directory, [f"Standard={directory / 'S.nulllib'}"])
            self.assertEqual(code, 0)
            self.assertEqual(parsed_bytes((directory / "h.h").read_text()), b"abc")

    def test_invalid_identifier_fails(self) -> None:
        for bad in ("2Fast", "my-shader"):
            with self.subTest(name=bad), tempfile.TemporaryDirectory() as name:
                directory = Path(name)
                (directory / "L").write_bytes(b"abc")
                (directory / "h.h").write_text("old")
                code, message = self.run_main(directory, [f"{bad}={directory / 'L'}"])
                self.assertEqual(code, 1)
                self.assertIn("embed_library:", message)
                self.assertEqual((directory / "h.h").read_text(), "old")

    def test_empty_library_fails(self) -> None:
        with tempfile.TemporaryDirectory() as name:
            directory = Path(name)
            (directory / "L").write_bytes(b"")
            (directory / "h.h").write_text("old")
            code, message = self.run_main(directory, [f"A={directory / 'L'}"])
            self.assertEqual(code, 1)
            self.assertIn("embed_library:", message)
            self.assertEqual((directory / "h.h").read_text(), "old")

    def test_missing_library_fails(self) -> None:
        with tempfile.TemporaryDirectory() as name:
            directory = Path(name)
            (directory / "h.h").write_text("old")
            code, message = self.run_main(directory, [f"A={directory / 'none'}"])
            self.assertEqual(code, 1)
            self.assertIn(str(directory / "none"), message)
            self.assertEqual((directory / "h.h").read_text(), "old")

    def test_duplicate_name_fails(self) -> None:
        with tempfile.TemporaryDirectory() as name:
            directory = Path(name)
            (directory / "L").write_bytes(b"abc")
            (directory / "h.h").write_text("old")
            code, message = self.run_main(directory, [f"A={directory / 'L'}", f"A={directory / 'L'}"])
            self.assertEqual(code, 1)
            self.assertIn("'A'", message)
            self.assertEqual((directory / "h.h").read_text(), "old")


if __name__ == "__main__":
    unittest.main()
