#!/usr/bin/env python3
"""Write a C++ header that embeds shader library bytes as rojoRHI::embedded::k<Name>Library.

Each --library NAME=PATH becomes one array in the header, in the order given:

  inline constexpr std::byte k<Name>Library[] = { std::byte{0x72}, ... };

preceded by a comment naming the --format (metal4, d3d12 or null) and NAME.slang. The header is
rewritten only when its text changes, so an unchanged library leaves its modification time alone.
"""

from __future__ import annotations

import argparse
import os
import re
import sys
import tempfile
from pathlib import Path

NAME_PATTERN = re.compile(r"[A-Za-z_][A-Za-z0-9_]*")
BYTES_PER_ROW = 16


class EmbedError(Exception):
    """An input that cannot be embedded."""


def array_text(format: str, name: str, data: bytes) -> str:
    rows = []
    for start in range(0, len(data), BYTES_PER_ROW):
        row = ", ".join(f"std::byte{{0x{byte:02x}}}" for byte in data[start : start + BYTES_PER_ROW])
        rows.append(f"        {row},\n")
    return (
        f"    /// The {format} shader library of {name}.slang.\n"
        f"    inline constexpr std::byte k{name}Library[] = {{\n" + "".join(rows) + "    };\n"
    )


def header_text(format: str, libraries: list[tuple[str, bytes]]) -> str:
    arrays = "\n".join(array_text(format, name, data) for name, data in libraries)
    return (
        "// Generated by rojorhi.slang; do not edit.\n"
        "#pragma once\n"
        "\n"
        "#include <cstddef>\n"
        "\n"
        "namespace rojoRHI::embedded {\n" + arrays + "} // namespace rojoRHI::embedded\n"
    )


def created_file_mode() -> int:
    """The mode open() gives a new file under the process umask; mkstemp alone gives 0600."""
    umask = os.umask(0)
    os.umask(umask)
    return 0o666 & ~umask


def write_if_changed(path: Path, text: str) -> bool:
    data = text.encode("utf-8")
    try:
        if path.read_bytes() == data:
            return False
    except OSError:
        pass
    descriptor, temporary = tempfile.mkstemp(dir=path.parent, prefix=f".{path.name}.")
    try:
        with os.fdopen(descriptor, "wb") as stream:
            stream.write(data)
        os.chmod(temporary, created_file_mode())
        os.replace(temporary, path)
    except BaseException:
        Path(temporary).unlink(missing_ok=True)
        raise
    return True


def library_argument(text: str) -> tuple[str, Path]:
    name, separator, path = text.partition("=")
    if not separator or not path:
        raise argparse.ArgumentTypeError(f"'{text}' is not NAME=PATH")
    return name, Path(path)


def read_libraries(arguments: list[tuple[str, Path]]) -> list[tuple[str, bytes]]:
    libraries: list[tuple[str, bytes]] = []
    seen: set[str] = set()
    for name, path in arguments:
        if not NAME_PATTERN.fullmatch(name):
            raise EmbedError(f"library name '{name}' is not [A-Za-z_][A-Za-z0-9_]*")
        if name in seen:
            raise EmbedError(f"library '{name}' is given twice")
        seen.add(name)
        try:
            data = path.read_bytes()
        except OSError as error:
            raise EmbedError(f"{path}: cannot read: {error}") from error
        if not data:
            raise EmbedError(f"{path}: the library is empty")
        libraries.append((name, data))
    return libraries


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", required=True, type=Path, help="header to write")
    parser.add_argument("--format", required=True, choices=("metal4", "d3d12", "null"), help="library format")
    parser.add_argument(
        "--library", action="append", required=True, type=library_argument, metavar="NAME=PATH",
        help="library to embed as k<NAME>Library, once for each library",
    )  # fmt: skip
    args = parser.parse_args(argv)
    try:
        text = header_text(args.format, read_libraries(args.library))
        write_if_changed(args.out, text)
    except (EmbedError, OSError) as error:
        print(f"embed_library: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
