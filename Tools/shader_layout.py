#!/usr/bin/env python3
"""Generate static_asserts that pin C++ struct layouts to the offsets Slang reflects on every target.

Each input is `<target>=<reflection.json>`, the `-reflection-json` output of one probe compile. The probe
declares a `StructuredBuffer<T>` per shared struct and names it by role:

  gRecord_<Name>   data behind an address, natural layout, any field type
  gRoot_<Name>     a root block, which must also satisfy the flat root rules of the shader ABI chapter

`<Name>` maps to the C++ type `rojoRHI::<Name>` unless `--map Name=Type` says otherwise.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path


RECORD_PREFIX = "gRecord_"
ROOT_PREFIX = "gRoot_"
ROOT_MAX_BYTES = 65536
ROOT_SIZE_MULTIPLE = 16
ROOT_SCALARS = {"uint32", "int32", "float32"}


class LayoutError(Exception):
    """A probe that cannot be compared or a root that breaks the flat root rules."""


class Struct:
    def __init__(self, name: str, is_root: bool, size: int, fields: list[tuple[str, int, dict]]) -> None:
        self.name = name
        self.is_root = is_root
        self.size = size
        self.fields = fields


def read_struct(parameter: dict, target: str) -> Struct:
    name = parameter["name"]
    is_root = name.startswith(ROOT_PREFIX)
    short = name[len(ROOT_PREFIX if is_root else RECORD_PREFIX):]
    result = parameter.get("type", {}).get("resultType")
    if not result or result.get("kind") != "struct":
        raise LayoutError(f"{short} on {target}: parameter {name} is not a StructuredBuffer of a struct")
    fields = [(f["name"], f["binding"]["offset"], f["type"]) for f in result["fields"]]
    return Struct(short, is_root, result["sizes"][0]["value"], fields)


def read_structs(reflection: dict, target: str) -> dict[str, Struct]:
    structs: dict[str, Struct] = {}
    for parameter in reflection["parameters"]:
        if parameter["name"].startswith((RECORD_PREFIX, ROOT_PREFIX)):
            struct = read_struct(parameter, target)
            structs[struct.name] = struct
    return structs


def root_alignment(struct: Struct, field: str, type_: dict, target: str) -> int:
    where = f"{struct.name}.{field} on {target}"
    kind = type_.get("kind")
    if kind == "struct":
        raise LayoutError(f"{where}: nested struct breaks the flat root rules")
    if kind == "scalar":
        scalar, count = type_.get("scalarType"), 1
    elif kind == "vector":
        scalar, count = type_["elementType"].get("scalarType"), type_["elementCount"]
    else:
        raise LayoutError(f"{where}: {kind} is not a 32-bit scalar, 2- or 4-vector, or Addr")
    if scalar not in ROOT_SCALARS:
        raise LayoutError(f"{where}: {scalar} is not a 32-bit scalar; a 64-bit scalar breaks the flat root rules")
    if count == 3:
        raise LayoutError(f"{where}: 3-vector breaks the flat root rules")
    return 4 * count


def check_root(struct: Struct, target: str) -> None:
    for field, offset, type_ in struct.fields:
        alignment = root_alignment(struct, field, type_, target)
        if offset % alignment:
            raise LayoutError(f"{struct.name}.{field} on {target}: offset {offset} is not aligned to {alignment}")
    if struct.size % ROOT_SIZE_MULTIPLE:
        raise LayoutError(f"{struct.name} on {target}: size {struct.size} is not a multiple of 16")
    if struct.size > ROOT_MAX_BYTES:
        raise LayoutError(f"{struct.name} on {target}: size {struct.size} is above {ROOT_MAX_BYTES} bytes")


def generate(
    reflections: dict[str, dict],
    type_map: dict[str, str] | None = None,
    includes: list[str] | None = None,
) -> str:
    type_map = type_map or {}
    per_target = {target: read_structs(reflection, target) for target, reflection in reflections.items()}
    names = sorted({name for structs in per_target.values() for name in structs})
    for target, structs in per_target.items():
        for name in names:
            if name not in structs:
                raise LayoutError(f"{name} is missing from the probe on {target}")
    lines = ["// Generated by Tools/shader_layout.py; do not edit.", "#pragma once", "", "#include <cstddef>"]
    lines += [f"#include <{include}>" for include in includes or []]
    lines += [""]
    for name in names:
        cpp = type_map.get(name, f"rojoRHI::{name}")
        for target, structs in per_target.items():
            struct = structs[name]
            if struct.is_root:
                check_root(struct, target)
            for field, offset, _ in struct.fields:
                lines.append(f"static_assert(offsetof({cpp}, {field}) == {offset},")
                lines.append(f'              "{name}.{field}: offset {offset} on {target}");')
            lines.append(f"static_assert(sizeof({cpp}) == {struct.size},")
            lines.append(f'              "{name}: size {struct.size} on {target}");')
        lines.append("")
    lines.append(f"inline constexpr int kShaderLayoutStructCount = {len(names)};")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("inputs", nargs="+", help="<target>=<reflection.json>")
    parser.add_argument("--out", required=True, type=Path)
    parser.add_argument("--map", action="append", default=[], help="Name=CppType, default rojoRHI::Name")
    parser.add_argument("--include", action="append", default=[], help="header the C++ types come from")
    args = parser.parse_args(argv)
    try:
        reflections = {}
        for item in args.inputs:
            target, _, path = item.partition("=")
            reflections[target] = json.loads(Path(path).read_text())
        type_map = dict(item.split("=", 1) for item in args.map)
        text = generate(reflections, type_map, args.include)
    except (LayoutError, OSError, ValueError, KeyError) as error:
        print(f"shader layout check failed: {error}", file=sys.stderr)
        return 1
    args.out.parent.mkdir(parents=True, exist_ok=True)
    if not args.out.exists() or args.out.read_text() != text:
        args.out.write_text(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
